#!/usr/bin/env python
"""TwistedMerge++ period-index detector demo."""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.metrics import capture_environment, save_json  # noqa: E402
from src.model_merging_benchmark import format_markdown_table, permutation_matrix  # noqa: E402
from src.period_index_central import heisenberg_generators  # noqa: E402
from src.twisted_merge_plus import TwistedMergePlus  # noqa: E402


def git_commit() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, text=True).strip()
    except Exception:
        return "unknown"


def generator_dict(d: int, k: int) -> dict[str, np.ndarray]:
    system = heisenberg_generators(d, k)
    generators: dict[str, np.ndarray] = {}
    for idx in range(k):
        generators[f"U{idx + 1}"] = system.U[idx]
        generators[f"V{idx + 1}"] = system.V[idx]
    return generators


def unresolved_pairwise(width: int) -> dict[tuple[int, int], np.ndarray]:
    diagonal = np.diag(np.linspace(1.0, 2.0, width)).astype(complex)
    return {
        (0, 0): np.eye(width, dtype=complex),
        (1, 1): np.eye(width, dtype=complex),
        (2, 2): np.eye(width, dtype=complex),
        (0, 1): diagonal,
        (1, 2): np.eye(width, dtype=complex),
        (2, 0): np.eye(width, dtype=complex),
    }


def s3_noncentral_generators() -> dict[str, np.ndarray]:
    return {
        "s12": permutation_matrix(np.array([1, 0, 2])),
        "s23": permutation_matrix(np.array([0, 2, 1])),
    }


def run_scenario(tmpp: TwistedMergePlus, scenario: str, d: int, k: int, rank: int) -> dict:
    width = d**k
    result = tmpp.run(
        unresolved_pairwise(width),
        n_models=3,
        width=width,
        period_index_generators=generator_dict(d, k),
        candidate_lift_rank=rank,
    )
    return pack_row(scenario, d, k, rank, result)


def pack_row(scenario: str, d: int | None, k: int | None, rank: int, result) -> dict:
    detector = result.diagnostics.period_index
    return {
        "scenario": scenario,
        "d": d,
        "k": k,
        "period": detector.period if detector is not None else None,
        "index": detector.index if detector is not None else None,
        "candidate_rank": rank,
        "period_divides_rank": detector.period_divides_rank if detector is not None else None,
        "index_divides_rank": detector.index_divides_rank if detector is not None else None,
        "classification": result.diagnostics.classification,
        "selected_method": result.selected_method,
        "centrality_score": detector.centrality_score if detector is not None else result.diagnostics.centrality_score,
        "phase_residual": detector.phase_residual if detector is not None else result.diagnostics.phase_residual,
        "independent_pair_count": detector.independent_pair_count if detector is not None else None,
        "detector_decision": detector.decision if detector is not None else None,
        "reason": result.reason,
    }


def scenario_rows() -> list[dict]:
    tmpp = TwistedMergePlus()
    rows = [
        run_scenario(tmpp, "d2_k1_rank2", 2, 1, 2),
        run_scenario(tmpp, "d2_k2_rank2", 2, 2, 2),
        run_scenario(tmpp, "d2_k2_rank4", 2, 2, 4),
        run_scenario(tmpp, "d2_k3_rank2", 2, 3, 2),
        run_scenario(tmpp, "d2_k3_rank4", 2, 3, 4),
        run_scenario(tmpp, "d2_k3_rank8", 2, 3, 8),
        run_scenario(tmpp, "d3_k2_rank3", 3, 2, 3),
        run_scenario(tmpp, "d3_k2_rank6", 3, 2, 6),
        run_scenario(tmpp, "d3_k2_rank9", 3, 2, 9),
    ]
    result = tmpp.run(
        unresolved_pairwise(3),
        n_models=3,
        width=3,
        period_index_generators=s3_noncentral_generators(),
        candidate_lift_rank=3,
    )
    rows.append(pack_row("noncentral_control", None, None, 3, result))
    return rows


def write_report(args, df: pd.DataFrame, path: Path) -> None:
    columns = [
        "scenario",
        "d",
        "k",
        "period",
        "index",
        "candidate_rank",
        "period_divides_rank",
        "index_divides_rank",
        "classification",
        "selected_method",
        "centrality_score",
        "phase_residual",
        "independent_pair_count",
        "reason",
    ]
    d3k2 = df[df["scenario"].isin(["d3_k2_rank3", "d3_k2_rank6", "d3_k2_rank9"])]
    d2k3 = df[df["scenario"].isin(["d2_k3_rank2", "d2_k3_rank4", "d2_k3_rank8"])]

    report = f"""# TwistedMerge++ Period-Index Report

This report is generated by `experiments/twisted_merge_plus_period_index_demo.py`.

## Exact Command

```bash
{args.command_string}
```

## Commit Hash

`{git_commit()}`

## Detector Upgrade

The one-pair finite-index detector checks the basic case where period equals
index.  The period-index detector uses multi-generator central commutator data
to recognize controlled finite Heisenberg systems where period is `d` but the
index is `d^k`.  A rank divisible by the period is not accepted unless it is
also divisible by the computed index.

## Scenario Table

{format_markdown_table(df.to_dict("records"), columns)}

## Explicit Examples

For `d=3,k=2`, period is `3` and index is `9`; ranks `3` and `6` fail, while
rank `9` succeeds:

{format_markdown_table(d3k2.to_dict("records"), columns)}

For `d=2,k=3`, period is `2` and index is `8`; ranks `2` and `4` fail, while
rank `8` succeeds:

{format_markdown_table(d2k3.to_dict("records"), columns)}

## Algorithmic Conclusion

- TwistedMerge++ now rejects period-only rank claims for supplied central
  period-index generator data.
- It requires index divisibility before selecting
  `period_index_projective_morita_lift`.
- Scalar central commutators with unrecognized invariant structure are marked
  `central_projective_index_unknown`; no lift is claimed.
- Noncentral generator commutators remain rejected rather than relabeled as
  Brauer/projective classes.

## Negative Boundaries

- This is controlled central/projective evidence.
- It does not show real MNIST/CIFAR residuals are Brauer classes.
- It does not show TwistedMerge++ beats C2M3 on natural model merging.
- It does not trivialize the original class on the same cover; the selected
  lift is a finite-rank projective/Morita lift.

## Environment

```json
{json.dumps(capture_environment(), indent=2)}
```
"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(report, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--reports-dir", type=Path, default=ROOT / "reports")
    args = parser.parse_args()
    args.command_string = " ".join([sys.executable, *sys.argv])

    df = pd.DataFrame(scenario_rows())
    csv_path = args.reports_dir / "csv" / "twisted_merge_plus_period_index_demo.csv"
    report_path = args.reports_dir / "twisted_merge_plus_period_index_report.md"
    config_path = args.reports_dir / "configs" / "twisted_merge_plus_period_index_demo_config.json"
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(csv_path, index=False)
    save_json(
        config_path,
        {
            "argv": sys.argv,
            "environment": capture_environment(),
            "commit": git_commit(),
        },
    )
    write_report(args, df, report_path)
    print(f"wrote {csv_path}")
    print(f"wrote {report_path}")


if __name__ == "__main__":
    main()
